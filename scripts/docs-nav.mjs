// The documentation sidebar and the prev/next pager, in one place.
//
// The site is static HTML with no build step, so every page used to carry its own copy
// of the sidebar: seventeen copies of the same twenty lines, plus a hand written pager
// on each page that had to agree with the sidebar's order. Adding a page meant editing
// every other page, and a single missed file is the kind of drift nobody notices until a
// reader hits a dead link.
//
// So the order below is the only copy. Running this writes it into every page: the
// sidebar with aria-current on the page itself, and the pager from the page's neighbours
// in the same list. The pages stay plain HTML, which is the point: no client side
// rendering, so the nav is in the document for a reader with no JavaScript and for
// anything that indexes the site.
//
//   node scripts/docs-nav.mjs           write the nav into every page
//   node scripts/docs-nav.mjs --check   exit 1 if any page has drifted, write nothing
//
// src/lib/docsnav.test.js runs the check as part of `npm test`, so a hand edit to a
// generated block fails the suite instead of reaching the published site.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DOCS = join(ROOT, 'docs');

// Reading order. A section is a heading plus the pages under it; the pager walks this
// list flat, ignoring the headings, so prev/next cross a section boundary the way a
// reader does.
export const NAV = [
  {
    title: 'Ngintip docs',
    pages: [
      ['docs.html', 'Overview'],
      ['performance.html', 'Performance'],
    ],
  },
  {
    title: 'Getting started',
    pages: [
      ['install.html', 'Install'],
      ['start.html', 'First run and the CA'],
      ['browser.html', 'Built-in browser'],
    ],
  },
  {
    title: 'Capture',
    pages: [
      ['history.html', 'History'],
      ['intercept.html', 'Intercept'],
    ],
  },
  {
    title: 'Replay',
    pages: [
      ['repeater.html', 'Repeater'],
      ['intruder.html', 'Intruder'],
      ['organizer.html', 'Organizer'],
    ],
  },
  {
    title: 'Automation',
    pages: [
      ['automation.html', 'Rules and Passive Scan'],
      ['extensions.html', 'Extensions'],
      ['mcp.html', 'MCP server'],
    ],
  },
  {
    title: 'Reference',
    pages: [
      ['tools.html', 'Decoder and Comparer'],
      ['projects.html', 'Projects and Footprint'],
      ['about.html', 'About'],
    ],
  },
];

/** Every page in reading order, flat: [href, label]. */
export function pages() {
  return NAV.flatMap((section) => section.pages);
}

const GENERATED = 'Generated by scripts/docs-nav.mjs. Edit the list there, then run npm run docs:nav.';

/** The sidebar, with the current page marked. */
export function renderToc(href) {
  const lines = ['      <aside class="toc">', `        <!-- ${GENERATED} -->`, '        <nav aria-label="Documentation">'];
  for (const section of NAV) {
    lines.push(`          <p class="toc-title">${section.title}</p>`);
    for (const [to, label] of section.pages) {
      const current = to === href ? ' aria-current="page"' : '';
      lines.push(`          <a href="${to}"${current}>${label}</a>`);
    }
  }
  lines.push('        </nav>', '      </aside>');
  return lines.join('\n');
}

/** The prev/next pager for one page. The empty span keeps the other link to its side. */
export function renderPager(href) {
  const flat = pages();
  const i = flat.findIndex(([to]) => to === href);
  if (i < 0) throw new Error(`${href} is not in the nav`);
  const prev = flat[i - 1];
  const next = flat[i + 1];
  const lines = ['        <nav class="pager" aria-label="Page">'];
  lines.push(
    prev ? `          <a class="prev" href="${prev[0]}"><span>Previous</span>${prev[1]}</a>` : '          <span></span>',
  );
  lines.push(
    next ? `          <a class="next" href="${next[0]}"><span>Next</span>${next[1]}</a>` : '          <span></span>',
  );
  lines.push('        </nav>');
  return lines.join('\n');
}

// Anchored on the page's own structure rather than on marker comments, so a page that
// has never been through this script is still rewritten correctly the first time.
const TOC_BLOCK = /[ \t]*<aside class="toc">[\s\S]*?<\/aside>/;
const PAGER_BLOCK = /[ \t]*<nav class="pager"[\s\S]*?<\/nav>/;

/** What one page's file should contain. Throws if the page has no sidebar or no pager. */
export function render(href, source) {
  if (!TOC_BLOCK.test(source)) throw new Error(`${href} has no <aside class="toc"> block`);
  if (!PAGER_BLOCK.test(source)) throw new Error(`${href} has no <nav class="pager"> block`);
  // Function replacements, so a $ in a label could never be read as a backreference.
  return source.replace(TOC_BLOCK, () => renderToc(href)).replace(PAGER_BLOCK, () => renderPager(href));
}

/** Rewrite every page, or with { check: true } just report which ones differ. */
export function apply({ check = false } = {}) {
  const drifted = [];
  for (const [href] of pages()) {
    const path = join(DOCS, href);
    const source = readFileSync(path, 'utf8');
    const wanted = render(href, source);
    if (wanted === source) continue;
    drifted.push(href);
    if (!check) writeFileSync(path, wanted);
  }
  return drifted;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const drifted = apply({ check });
  const count = pages().length;
  if (!drifted.length) {
    console.log(`${count} pages, nav already in sync`);
  } else if (check) {
    console.error(`nav out of sync in ${drifted.length} of ${count} pages:`);
    for (const href of drifted) console.error(`  ${href}`);
    console.error('run: npm run docs:nav');
    process.exit(1);
  } else {
    console.log(`updated ${drifted.length} of ${count} pages:`);
    for (const href of drifted) console.log(`  ${href}`);
  }
}
